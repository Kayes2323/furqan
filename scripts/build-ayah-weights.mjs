// Derives per-ayah "letter counts" from the verbatim Tanzil dataset in
// public/quran/surah/*.json (read-only — the dataset itself is never
// modified). Output: app/lib/quran-ayah-weights.ts, used ONLY to weight
// reading-time estimates (a long ayah takes longer than a short one).
// Usage: node scripts/build-ayah-weights.mjs
import { readFileSync, writeFileSync } from 'node:fs';

// Arabic base letters U+0621..U+064A plus alef wasla U+0671 and
// superscript-alef-bearing forms are counted; diacritics/marks/spaces are not.
const LETTER = /[ء-يٱ-ۓ]/g;
const counts = [];
for (let s = 1; s <= 114; s++) {
  const doc = JSON.parse(readFileSync(`public/quran/surah/${String(s).padStart(3, '0')}.json`, 'utf8'));
  for (const a of doc.ayahs) counts.push((a.text.match(LETTER) ?? []).length);
}
if (counts.length !== 6236) throw new Error(`expected 6236 ayahs, got ${counts.length}`);
const out = `// GENERATED by scripts/build-ayah-weights.mjs from the Tanzil dataset — do not edit.
// Arabic letter count of each ayah in global reading order (6236 entries).
// Used only to weight reading-time estimates; never alters Quran text.
export const AYAH_LETTER_COUNTS: readonly number[] = [${counts.join(',')}];
`;
writeFileSync('app/lib/quran-ayah-weights.ts', out);
console.log('ayahs', counts.length, 'letters', counts.reduce((a, b) => a + b, 0), 'max', Math.max(...counts), 'min', Math.min(...counts));
